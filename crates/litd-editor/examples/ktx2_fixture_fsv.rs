use std::{fs, io};

use litd_editor::{
    asset_vault::AssetVaultCatalog,
    texture_import::{
        TextureRole, encode_rgba8_ktx2, import_texture_asset, validate_ktx2_texture_record,
    },
};
use serde_json::json;

#[path = "ktx2_fixture_fsv/support.rs"]
mod ktx2_fixture_fsv_support;

use ktx2_fixture_fsv_support::{
    FIXTURE_RELATIVE_PATH, SOURCE_PNG, edge_manifest_sha_mismatch_rejected,
    edge_truncated_ktx2_rejected, edge_wrong_extension_rejected, real_record, record_json,
    source_truth_state, upsert_manifest_record, validate_fixture_receipt, vault_root,
    write_fixture_file,
};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    litd_engine::init_logging();
    let (fsv_run, root) = litd_editor::fsv_support::artifact_dir_from_env(
        "LITD_KTX2_FIXTURE_FSV_ROOT",
        "issue1297_ktx2_fixture",
        "manual",
    )?;
    let fsv_json_path = root.join("ktx2_fixture_fsv.json");
    let stats_path = root.join("stats.txt");
    let vault_root = fs::canonicalize(vault_root())?;
    let manifest_path = vault_root
        .join("manifests")
        .join("asset_intake_manifest.jsonl");
    let extraction_manifest_path = vault_root
        .join("manifests")
        .join("asset_extraction_manifest.jsonl");
    let fixture_path = vault_root.join(FIXTURE_RELATIVE_PATH);

    let before_state = source_truth_state(&fixture_path, &manifest_path, &fsv_json_path)?;
    let source_catalog =
        AssetVaultCatalog::load_from_manifest(&extraction_manifest_path, "extraction")?;
    let source_record = real_record(&source_catalog, SOURCE_PNG)?;
    let source_texture = import_texture_asset(&source_record, TextureRole::UiSprite)?;
    let fixture = encode_rgba8_ktx2(
        &source_texture.receipt.source_relative_path,
        &source_texture.decoded_rgba8,
        source_texture.receipt.width,
        source_texture.receipt.height,
        "litd-editor issue1297 ktx2_fixture_fsv",
    )?;

    write_fixture_file(&fixture_path, &fixture.bytes)?;
    let fixture_bytes = fs::read(&fixture_path)?;
    if fixture_bytes != fixture.bytes {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "KTX2 fixture file readback did not match generated bytes",
        )
        .into());
    }

    let manifest_upsert = upsert_manifest_record(
        &manifest_path,
        &fixture_path,
        &source_record,
        fixture.bytes.len() as u64,
        &fixture.receipt.ktx2_sha256,
    )?;
    let verified_catalog = AssetVaultCatalog::load_default()?;
    let fixture_record = real_record(&verified_catalog, FIXTURE_RELATIVE_PATH)?;
    let ktx2_receipt = validate_ktx2_texture_record(&fixture_record)?;
    validate_fixture_receipt(&ktx2_receipt, &fixture.receipt)?;
    let after_happy_state = source_truth_state(&fixture_path, &manifest_path, &fsv_json_path)?;

    let edge_truncated = edge_truncated_ktx2_rejected(
        &root,
        &fixture_record,
        &fixture_path,
        &manifest_path,
        &fsv_json_path,
    )?;
    let edge_wrong_extension = edge_wrong_extension_rejected(
        &fixture_record,
        &fixture_path,
        &manifest_path,
        &fsv_json_path,
    )?;
    let edge_manifest_sha = edge_manifest_sha_mismatch_rejected(
        &fixture_record,
        &fixture_path,
        &manifest_path,
        &fsv_json_path,
    )?;

    let fsv = json!({
        "issue": 1297,
        "source_of_truth": "local-asset-vault asset_intake_manifest.jsonl row plus physical KTX2 file, reloaded through AssetVaultCatalog and validated by ktx2::Reader",
        "fixture_relative_path": FIXTURE_RELATIVE_PATH,
        "before_state": before_state,
        "after_happy_state": after_happy_state,
        "source_png_record": record_json(&source_record),
        "generated_ktx2": fixture.receipt,
        "manifest_upsert": manifest_upsert,
        "fixture_record_readback": record_json(&fixture_record),
        "ktx2_receipt_readback": ktx2_receipt,
        "edges": {
            "truncated_ktx2_rejected": edge_truncated.to_json(),
            "wrong_extension_rejected": edge_wrong_extension.to_json(),
            "manifest_sha_mismatch_rejected": edge_manifest_sha.to_json()
        }
    });
    fs::write(&fsv_json_path, serde_json::to_vec_pretty(&fsv)?)?;
    let fsv_bytes = fs::read(&fsv_json_path)?;
    let report_readback = fsv_run.record_json_file(&fsv_json_path)?;
    let after_artifact_state = source_truth_state(&fixture_path, &manifest_path, &fsv_json_path)?;
    fs::write(
        &stats_path,
        format!(
            "issue=1297\n\
             source_of_truth=local-asset-vault manifest row and physical KTX2 file\n\
             before_state={}\n\
             after_happy_state={}\n\
             after_artifact_state={}\n\
             fixture_relative_path={}\n\
             fixture_absolute_path={}\n\
             fixture_bytes={}\n\
             fixture_sha256={}\n\
             source_png={}\n\
             source_png_sha256={}\n\
             generated_width={}\n\
             generated_height={}\n\
             generated_vk_format={}\n\
             generated_level_byte_length={}\n\
             parsed_width={}\n\
             parsed_height={}\n\
             parsed_vk_format={}\n\
             parsed_level_bytes={}\n\
             manifest_action={}\n\
             manifest_before_sha256={}\n\
             manifest_after_sha256={}\n\
             fsv_json_path={}\n\
             fsv_json_bytes={}\n\
             fsv_json_sha256={}\n\
             edge_truncated_error={}\n\
             edge_truncated_before={}\n\
             edge_truncated_after={}\n\
             edge_wrong_extension_error={}\n\
             edge_wrong_extension_before={}\n\
             edge_wrong_extension_after={}\n\
             edge_manifest_sha_error={}\n\
             edge_manifest_sha_before={}\n\
             edge_manifest_sha_after={}\n",
            before_state,
            after_happy_state,
            after_artifact_state,
            FIXTURE_RELATIVE_PATH,
            fixture_record.absolute_path.display(),
            fixture_record.bytes_on_disk,
            fixture_record.sha256,
            source_record.relative_path,
            source_record.sha256,
            fixture.receipt.width,
            fixture.receipt.height,
            fixture.receipt.vk_format,
            fixture.receipt.level_byte_length,
            ktx2_receipt.width,
            ktx2_receipt.height,
            ktx2_receipt.vk_format,
            ktx2_receipt.level_bytes,
            manifest_upsert["action"],
            manifest_upsert["before_sha256"],
            manifest_upsert["after_sha256"],
            fsv_json_path.display(),
            fsv_bytes.len(),
            report_readback.sha256,
            edge_truncated.error,
            edge_truncated.before_state,
            edge_truncated.after_state,
            edge_wrong_extension.error,
            edge_wrong_extension.before_state,
            edge_wrong_extension.after_state,
            edge_manifest_sha.error,
            edge_manifest_sha.before_state,
            edge_manifest_sha.after_state,
        ),
    )?;
    println!(
        "wrote issue1297 KTX2 fixture FSV to {} and {}",
        fsv_json_path.display(),
        stats_path.display()
    );
    Ok(())
}
