use litd_editor::asset_scene::EditorFoliageReport;

pub(super) struct FoliageShellStats {
    pub(super) present: bool,
    pub(super) config_id: String,
    pub(super) tileset_id: String,
    pub(super) source_relative_path: String,
    pub(super) source_sha256: String,
    pub(super) brush_state_present: bool,
    pub(super) brush_state_source_path: String,
    pub(super) brush_state_sha256: String,
    pub(super) brush_stamp_count: usize,
    pub(super) brush_add_stamp_count: usize,
    pub(super) brush_erase_stamp_count: usize,
    pub(super) brush_added_patch_count: usize,
    pub(super) brush_erased_patch_count: usize,
    pub(super) schema_version: u32,
    pub(super) source_issue: u32,
    pub(super) prototype_count: usize,
    pub(super) patch_count: usize,
    pub(super) target_clump_count: u32,
    pub(super) placed_clump_count: u32,
    pub(super) foliage_index_count: u32,
    pub(super) density_scale: f32,
    pub(super) gpu_instancing_required: bool,
    pub(super) render_mode_summary: String,
    pub(super) cull_range_summary: String,
}

impl FoliageShellStats {
    pub(super) fn from(report: Option<&EditorFoliageReport>) -> Self {
        match report {
            Some(report) => Self {
                present: true,
                config_id: report.config_id.clone(),
                tileset_id: report.tileset_id.clone(),
                source_relative_path: report.source_relative_path.clone(),
                source_sha256: report.source_sha256.clone(),
                brush_state_present: report.brush_state_present,
                brush_state_source_path: report.brush_state_source_path.clone(),
                brush_state_sha256: report.brush_state_sha256.clone(),
                brush_stamp_count: report.brush_stamp_count,
                brush_add_stamp_count: report.brush_add_stamp_count,
                brush_erase_stamp_count: report.brush_erase_stamp_count,
                brush_added_patch_count: report.brush_added_patch_count,
                brush_erased_patch_count: report.brush_erased_patch_count,
                schema_version: report.schema_version,
                source_issue: report.source_issue,
                prototype_count: report.prototype_count,
                patch_count: report.patch_count,
                target_clump_count: report.target_clump_count,
                placed_clump_count: report.placed_clump_count,
                foliage_index_count: report.foliage_index_count,
                density_scale: report.density_scale,
                gpu_instancing_required: report.gpu_instancing_required,
                render_mode_summary: report.render_mode_summary.clone(),
                cull_range_summary: report.cull_range_summary.clone(),
            },
            None => Self {
                present: false,
                config_id: "none".to_string(),
                tileset_id: "none".to_string(),
                source_relative_path: "none".to_string(),
                source_sha256: "none".to_string(),
                brush_state_present: false,
                brush_state_source_path: "none".to_string(),
                brush_state_sha256: "none".to_string(),
                brush_stamp_count: 0,
                brush_add_stamp_count: 0,
                brush_erase_stamp_count: 0,
                brush_added_patch_count: 0,
                brush_erased_patch_count: 0,
                schema_version: 0,
                source_issue: 0,
                prototype_count: 0,
                patch_count: 0,
                target_clump_count: 0,
                placed_clump_count: 0,
                foliage_index_count: 0,
                density_scale: 0.0,
                gpu_instancing_required: false,
                render_mode_summary: "none".to_string(),
                cull_range_summary: "none".to_string(),
            },
        }
    }
}
