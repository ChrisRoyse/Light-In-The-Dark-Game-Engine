# Combines the numbered research docs in this folder into a single markdown file.
# Usage: powershell -File combine-docs.ps1   (run from anywhere; paths are script-relative)

$docDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$outFile = Join-Path $docDir "COMBINED-3d-world-tech-report.md"

$files = @(
    "00-final-report-and-recommendation.md",
    "01-repo-and-issues-briefing.md",
    "02-traditional-3d-rendering-research.md",
    "03-triangle-splatting-and-gaussian-splatting-research.md",
    "04-diffusion-world-models-and-neural-rendering-research.md"
)

$parts = @()
$parts += "# COMBINED: 3D World Technology Report -- Light in the Dark (2026-07-12)"
$parts += ""
$parts += "This file is generated by combine-docs.ps1 from the five source documents below."
$parts += "Do not edit directly; edit the source files and re-run the script."
$parts += ""
foreach ($f in $files) { $parts += "- $f" }

foreach ($f in $files) {
    $path = Join-Path $docDir $f
    if (-not (Test-Path $path)) { Write-Error "Missing source file: $path"; exit 1 }
    $parts += ""
    $parts += ("=" * 80)
    $parts += "# SOURCE FILE: $f"
    $parts += ("=" * 80)
    $parts += ""
    $parts += (Get-Content $path)
}

$parts | Out-File -FilePath $outFile -Encoding utf8
Write-Host "Wrote $outFile ($((Get-Item $outFile).Length) bytes, $($parts.Count) lines)"
